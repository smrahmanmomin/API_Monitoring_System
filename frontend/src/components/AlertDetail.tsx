import { ApiError } from '../api/client';
import type { AlertDetail as AlertDetailType } from '../api/types';
import { useAlert, useRegenerate, useUpdateStatus } from '../hooks/useMonitoring';
import { anomalyLabel, formatDateTime, formatMs, recordsLabel } from '../lib/format';
import { HttpCode, SeverityBadge, SourceTag, StatusTag } from './Badges';
import { ErrorState, LoadingRows } from './States';
import { useToast } from './Toasts';

interface Props {
  alertId: string;
  aiEnabled: boolean;
  onClose: () => void;
}

function Evidence({ alert }: { alert: AlertDetailType }) {
  const { check, finding, relatedFindings, escalation } = alert.evidence;
  const rows: Array<[string, React.ReactNode]> = [
    ['HTTP status', <HttpCode key="h" code={check.statusCode} />],
    ['Response time', `${formatMs(check.responseTimeMs)}${check.latencyThresholdMs ? ` (threshold ${formatMs(check.latencyThresholdMs)})` : ''}`],
    ['Records returned', recordsLabel({ records_returned: check.recordsReturned, records_issue: check.recordsIssue })],
  ];
  if (check.expectedMinRecords !== null) rows.push(['Expected minimum', String(check.expectedMinRecords)]);
  rows.push(['Checked at', formatDateTime(finding.checkedAt)]);

  return (
    <>
      <p className="rule-line">
        <span className="eyebrow">Rule</span> {finding.message}
      </p>
      <dl className="evidence">
        {rows.map(([k, v]) => (
          <div key={k}>
            <dt>{k}</dt>
            <dd className="mono">{v}</dd>
          </div>
        ))}
      </dl>
      {relatedFindings.length > 0 && (
        <p className="related">
          Same check also flagged:{' '}
          {relatedFindings.map((f) => (
            <span key={f.type} className="related-item">
              {anomalyLabel(f.type)} <small>({f.severity.toLowerCase()})</small>
            </span>
          ))}
        </p>
      )}
      {escalation && (
        <p className="escalation">
          Escalated {escalation.fromSeverity.toLowerCase()} → {escalation.toSeverity.toLowerCase()} after {escalation.occurrenceCount} occurrences.
        </p>
      )}
    </>
  );
}

export function AlertDetail({ alertId, aiEnabled, onClose }: Props) {
  const { data: alert, isLoading, error, refetch } = useAlert(alertId);
  const updateStatus = useUpdateStatus();
  const regenerate = useRegenerate();
  const toast = useToast();

  const changeStatus = (status: 'ACKNOWLEDGED' | 'RESOLVED') => {
    updateStatus.mutate(
      { id: alertId, status },
      {
        onSuccess: () => toast(status === 'ACKNOWLEDGED' ? 'Alert acknowledged' : 'Alert resolved'),
        onError: (e) => toast(e instanceof ApiError ? e.message : 'Could not update the alert', 'error'),
      },
    );
  };

  const regenerateText = () => {
    regenerate.mutate(alertId, {
      onSuccess: (r) => toast(r.generation_result === 'ai' ? 'Explanation regenerated by AI' : 'AI unavailable — rule-based text kept', r.generation_result === 'ai' ? 'success' : 'info'),
      onError: (e) => toast(e instanceof ApiError ? e.message : 'Could not regenerate the explanation', 'error'),
    });
  };

  return (
    <aside className="detail" aria-labelledby="detail-title">
      <div className="detail-bar">
        <span className="eyebrow">Alert detail</span>
        <button type="button" className="btn btn-quiet" onClick={onClose} aria-label="Close alert detail">
          Close
        </button>
      </div>

      {isLoading && <LoadingRows rows={6} label="Loading alert" />}
      {error && <ErrorState error={error} onRetry={() => void refetch()} />}

      {alert && (
        <div className="detail-body">
          <div className="detail-tags">
            <SeverityBadge severity={alert.severity} />
            <StatusTag status={alert.status} />
            <span className="type-tag">{anomalyLabel(alert.anomaly_type)}</span>
          </div>
          <h2 id="detail-title">{alert.title}</h2>
          <p className="detail-api mono">{alert.api_name}</p>

          <p className="summary">{alert.summary}</p>
          <p className="provenance">
            <SourceTag source={alert.generation.source} model={alert.generation.model} />
            {alert.generation.source === 'AI'
              ? ` Written by ${alert.generation.model ?? 'the LLM'} (${alert.generation.prompt_version}) from the evidence below. Severity was set by the rules.`
              : ' Written by deterministic rules. No LLM output used.'}
          </p>

          <section>
            <h3>Recommended actions</h3>
            <ol className="actions-list">
              {alert.recommended_actions.map((a) => (
                <li key={a}>{a}</li>
              ))}
            </ol>
          </section>

          <section>
            <h3>
              Possible causes <span className="h-note">hypotheses, not verified</span>
            </h3>
            <ul className="causes-list">
              {alert.possible_causes.map((c) => (
                <li key={c}>{c}</li>
              ))}
            </ul>
          </section>

          <section>
            <h3>Evidence</h3>
            <Evidence alert={alert} />
          </section>

          <section>
            <h3>History</h3>
            <dl className="evidence">
              <div><dt>Occurrences</dt><dd className="mono">{alert.occurrence_count}</dd></div>
              <div><dt>First seen</dt><dd className="mono">{formatDateTime(alert.first_seen_at)}</dd></div>
              <div><dt>Last seen</dt><dd className="mono">{formatDateTime(alert.last_seen_at)}</dd></div>
              {alert.acknowledged_at && <div><dt>Acknowledged</dt><dd className="mono">{formatDateTime(alert.acknowledged_at)}</dd></div>}
              {alert.resolved_at && <div><dt>Resolved</dt><dd className="mono">{formatDateTime(alert.resolved_at)}</dd></div>}
            </dl>
            {alert.recent_occurrences.length > 1 && (
              <ol className="occurrences">
                {alert.recent_occurrences.map((o) => (
                  <li key={o.check.id} className="mono">
                    <span>{formatDateTime(o.check.checked_at)}</span>
                    <HttpCode code={o.check.status_code} />
                    <span>{formatMs(o.check.response_time_ms)}</span>
                    <span>
                      {recordsLabel(o.check)}
                      {o.check.records_returned !== null ? ' rec' : ''}
                    </span>
                  </li>
                ))}
              </ol>
            )}
          </section>

          <div className="detail-actions">
            {alert.status === 'ACTIVE' && (
              <button type="button" className="btn btn-secondary" disabled={updateStatus.isPending} onClick={() => changeStatus('ACKNOWLEDGED')}>
                Acknowledge
              </button>
            )}
            {alert.status !== 'RESOLVED' && (
              <button type="button" className="btn btn-primary" disabled={updateStatus.isPending} onClick={() => changeStatus('RESOLVED')}>
                Resolve
              </button>
            )}
            {alert.status !== 'RESOLVED' && aiEnabled && (
              <button type="button" className="btn btn-quiet" disabled={regenerate.isPending} onClick={regenerateText}>
                {regenerate.isPending ? 'Regenerating…' : 'Regenerate explanation'}
              </button>
            )}
            {alert.status === 'RESOLVED' && <p className="section-note">Resolved. If this anomaly happens again, a new alert opens.</p>}
          </div>
        </div>
      )}
    </aside>
  );
}
