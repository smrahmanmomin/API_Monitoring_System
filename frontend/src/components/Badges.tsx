import type { AlertStatus, Severity } from '../api/types';
import { statusTone } from '../lib/format';

export function SeverityBadge({ severity }: { severity: Severity }) {
  return (
    <span className={`sev sev-${severity.toLowerCase()}`}>
      <span className="sev-mark" aria-hidden="true" />
      {severity.charAt(0) + severity.slice(1).toLowerCase()}
    </span>
  );
}

const STATUS_LABEL: Record<AlertStatus, string> = { ACTIVE: 'Active', ACKNOWLEDGED: 'Acknowledged', RESOLVED: 'Resolved' };

export function StatusTag({ status }: { status: AlertStatus }) {
  return <span className={`status status-${status.toLowerCase()}`}>{STATUS_LABEL[status]}</span>;
}

export function HttpCode({ code }: { code: number }) {
  return <span className={`http http-${statusTone(code)}`}>{code}</span>;
}

/** Makes it explicit whether text came from the LLM or the deterministic fallback. */
export function SourceTag({ source, model }: { source: 'AI' | 'FALLBACK'; model?: string | null }) {
  return source === 'AI' ? (
    <span className="origin origin-ai" title={model ? `Generated by ${model}` : 'AI generated'}>AI</span>
  ) : (
    <span className="origin origin-rule" title="Deterministic rule-based text (LLM not used or unavailable)">Rule</span>
  );
}

export function DemoTag() {
  return <span className="demo-tag" title="Sample data submitted from this dashboard or the seed script">Demo</span>;
}
